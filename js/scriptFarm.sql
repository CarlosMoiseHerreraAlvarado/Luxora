CREATE TABLE IF NOT EXISTS app_users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(60) NOT NULL,
    full_name VARCHAR(160) NOT NULL,
    email VARCHAR(160),
    password_hash TEXT NOT NULL,
    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_app_users_username UNIQUE (username),
    CONSTRAINT uq_app_users_email UNIQUE (email),
    CONSTRAINT ck_app_users_role CHECK (role IN ('AUXILIAR', 'ENCARGADO', 'ADMINISTRADOR'))
);

CREATE TABLE IF NOT EXISTS suppliers (
    supplier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    tax_id VARCHAR(40),
    contact_name VARCHAR(120),
    phone VARCHAR(40),
    email VARCHAR(160),
    address VARCHAR(240),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_suppliers_tax_id UNIQUE (tax_id)
);

CREATE TABLE IF NOT EXISTS locations (
    location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    location_type VARCHAR(20) NOT NULL,
    temperature_min NUMERIC(5, 2),
    temperature_max NUMERIC(5, 2),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_locations_name UNIQUE (name),
    CONSTRAINT ck_locations_type CHECK (location_type IN ('GENERAL', 'FRIO', 'CUARENTENA', 'VENCIDOS', 'DANADOS', 'DEVOLUCIONES')),
    CONSTRAINT ck_locations_temperature CHECK (temperature_min IS NULL OR temperature_max IS NULL OR temperature_min <= temperature_max)
);

CREATE TABLE IF NOT EXISTS medications (
    medication_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    internal_code VARCHAR(40) NOT NULL,
    generic_name VARCHAR(180) NOT NULL,
    commercial_name VARCHAR(180),
    concentration VARCHAR(100),
    dosage_form VARCHAR(80),
    presentation VARCHAR(120),
    unit_measure VARCHAR(30) NOT NULL DEFAULT 'UNIDAD',
    minimum_stock NUMERIC(12, 2) NOT NULL DEFAULT 0,
    sale_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    requires_refrigeration BOOLEAN NOT NULL DEFAULT FALSE,
    controlled BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_medications_internal_code UNIQUE (internal_code),
    CONSTRAINT ck_medications_minimum_stock CHECK (minimum_stock >= 0),
    CONSTRAINT ck_medications_sale_price CHECK (sale_price >= 0)
);

