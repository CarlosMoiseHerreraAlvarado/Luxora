CREATE OR REPLACE VIEW v_inventory_alerts AS
WITH med_stock AS (
    SELECT m.medication_id,
           COALESCE(SUM(CASE WHEN b.status = 'DISPONIBLE' AND b.expiration_date >= CURRENT_DATE THEN b.current_quantity ELSE 0 END), 0) AS avail_qty
    FROM medications m
    LEFT JOIN batches b ON b.medication_id = m.medication_id
    GROUP BY m.medication_id
)
SELECT b.batch_id, m.internal_code, m.generic_name, b.batch_number,
       b.expiration_date, b.current_quantity, b.status,
       CASE
           WHEN b.status IN ('RETIRADO', 'DANADO', 'DEVUELTO', 'BLOQUEADO') THEN 'NO_DISPONIBLE'
           WHEN b.expiration_date < CURRENT_DATE THEN 'VENCIDO'
           WHEN b.expiration_date <= CURRENT_DATE + INTERVAL '30 days' THEN 'VENCE_PRONTO'
           WHEN ms.avail_qty <= m.minimum_stock THEN 'STOCK_MINIMO'
           ELSE NULL
       END AS alert_type
FROM batches b
JOIN medications m ON m.medication_id = b.medication_id
JOIN med_stock ms ON ms.medication_id = m.medication_id
WHERE m.active = TRUE
  AND (
      (b.current_quantity > 0 AND b.status IN ('RETIRADO', 'DANADO', 'DEVUELTO', 'BLOQUEADO'))
      OR (b.current_quantity > 0 AND b.expiration_date <= CURRENT_DATE + INTERVAL '30 days')
      OR (ms.avail_qty <= m.minimum_stock AND (b.current_quantity > 0 OR ms.avail_qty = 0))
  );

CREATE OR REPLACE VIEW v_movement_history AS
SELECT im.movement_id, im.movement_type, im.reference_number, im.reason,
       im.status, im.occurred_at, u.username AS performed_by_username,
       md.movement_detail_id, md.quantity, md.unit_cost,
       b.batch_id, b.batch_number, m.internal_code, m.generic_name
FROM inventory_movements im
JOIN app_users u ON u.user_id = im.performed_by
JOIN movement_details md ON md.movement_id = im.movement_id
JOIN batches b ON b.batch_id = md.batch_id
JOIN medications m ON m.medication_id = b.medication_id;

CREATE OR REPLACE VIEW v_invoice_history AS
WITH line_totals AS (
    SELECT invoice_id,
           COUNT(*) AS line_count,
           COALESCE(SUM(line_total), 0) AS calculated_subtotal
    FROM invoice_lines
    GROUP BY invoice_id
), payment_totals AS (
    SELECT invoice_id,
           COALESCE(SUM(amount), 0) AS paid_amount,
           COALESCE(SUM(change_amount), 0) AS change_amount,
           string_agg(DISTINCT payment_method, ', ' ORDER BY payment_method) AS payment_methods
    FROM invoice_payments
    GROUP BY invoice_id
)
SELECT i.invoice_id,
       i.series_code,
       i.document_number,
       i.document_type,
       i.status,
       i.currency_code,
       i.customer_id,
       i.customer_name_snapshot AS customer_name,
       i.customer_tax_id_snapshot AS customer_tax_id,
       u.username AS cashier_username,
       i.subtotal,
       i.discount_total,
       i.total,
       COALESCE(lt.line_count, 0) AS line_count,
       COALESCE(lt.calculated_subtotal, 0) AS calculated_subtotal,
       COALESCE(pt.paid_amount, 0) AS paid_amount,
       COALESCE(pt.change_amount, 0) AS change_amount,
       pt.payment_methods,
       i.issued_at,
       i.cancelled_at
FROM invoices i
JOIN app_users u ON u.user_id = i.cashier_id
LEFT JOIN line_totals lt ON lt.invoice_id = i.invoice_id
LEFT JOIN payment_totals pt ON pt.invoice_id = i.invoice_id;

