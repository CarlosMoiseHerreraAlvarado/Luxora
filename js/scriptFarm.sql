CREATE TABLE IF NOT EXISTS invoices (
    invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_code VARCHAR(10) NOT NULL DEFAULT 'FAC',
    document_number BIGINT GENERATED BY DEFAULT AS IDENTITY,
    document_type VARCHAR(30) NOT NULL DEFAULT 'INTERNAL_SALE',
    customer_id BIGINT REFERENCES customers (customer_id),
    customer_name_snapshot VARCHAR(160) NOT NULL DEFAULT 'Consumidor final',
    customer_tax_id_snapshot VARCHAR(40),
    customer_email_snapshot VARCHAR(160),
    cashier_id BIGINT NOT NULL REFERENCES app_users (user_id),
    status VARCHAR(20) NOT NULL DEFAULT 'ISSUED',
    currency_code CHAR(3) NOT NULL DEFAULT 'USD',
    subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0,
    discount_total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    issued_at TIMESTAMPTZ DEFAULT NOW(),
    cancelled_at TIMESTAMPTZ,
    cancellation_reason VARCHAR(240),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_invoices_series_number UNIQUE (series_code, document_number),
    CONSTRAINT ck_invoices_type CHECK (document_type IN ('INTERNAL_SALE')),
    CONSTRAINT ck_invoices_status CHECK (status IN ('DRAFT', 'ISSUED', 'CANCELLED')),
    CONSTRAINT ck_invoices_amounts CHECK (subtotal >= 0 AND discount_total >= 0 AND total >= 0),
    CONSTRAINT ck_invoices_total CHECK (total = subtotal - discount_total),
    CONSTRAINT ck_invoices_currency CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_invoices_cancellation_reason CHECK (status <> 'CANCELLED' OR length(btrim(cancellation_reason)) >= 5)
