CREATE TABLE IF NOT EXISTS batches (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medication_id BIGINT NOT NULL REFERENCES medications (medication_id),
    supplier_id BIGINT REFERENCES suppliers (supplier_id),
    location_id BIGINT NOT NULL REFERENCES locations (location_id),
    batch_number VARCHAR(80) NOT NULL,
    manufacture_date DATE,
    expiration_date DATE NOT NULL,
    received_quantity NUMERIC(12, 2) NOT NULL DEFAULT 0,
    current_quantity NUMERIC(12, 2) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_batches_medication_number_location UNIQUE (medication_id, batch_number, location_id),
    CONSTRAINT ck_batches_dates CHECK (manufacture_date IS NULL OR expiration_date >= manufacture_date),
    CONSTRAINT ck_batches_received_quantity CHECK (received_quantity >= 0),
    CONSTRAINT ck_batches_current_quantity CHECK (current_quantity >= 0),
    CONSTRAINT ck_batches_status CHECK (status IN ('CUARENTENA', 'DISPONIBLE', 'BLOQUEADO', 'VENCIDO', 'DEVUELTO', 'RETIRADO', 'DANADO'))
