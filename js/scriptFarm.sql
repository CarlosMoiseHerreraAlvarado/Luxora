CREATE OR REPLACE VIEW v_inventory_stock AS
SELECT m.medication_id, m.internal_code, m.generic_name, m.commercial_name,
       m.minimum_stock,
       COALESCE(SUM(CASE WHEN b.status IN ('CUARENTENA', 'DISPONIBLE') THEN b.current_quantity ELSE 0 END), 0) AS total_quantity,
       COUNT(b.batch_id) AS batch_count,
       m.sale_price,
       COALESCE(SUM(CASE WHEN b.status = 'DISPONIBLE' AND b.expiration_date >= CURRENT_DATE THEN b.current_quantity ELSE 0 END), 0) AS available_quantity
FROM medications m
LEFT JOIN batches b ON b.medication_id = m.medication_id
WHERE m.active = TRUE
GROUP BY m.medication_id, m.internal_code, m.generic_name, m.commercial_name, m.minimum_stock, m.sale_price;

